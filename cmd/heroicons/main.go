type flags struct {
	Root   string
	Output string
}

func ToCamelCase(filepath string) string {
	parts := strings.Split(filepath, "-")
	for i := range parts {
		parts[i] = cases.Title(language.English).String(parts[i])
	}

	return strings.Join(parts, "")
}

func main() {
	log.SetFlags(0)
	log.SetOutput(os.Stderr)

	//nolint:errcheck
	logx.RedirectStdLog(logx.LogSink)

	f := &flags{
		Root:   defaultRoot,
		Output: "icons/heroicons",
	}

	pflag.StringVar(&f.Output, "output", f.Output, "output")
	pflag.StringVar(&f.Root, "root", f.Root, "root")
	pflag.Parse()

	for _, v := range variants {
		path := filepath.Join(defaultRoot, v.Path)
		err := filepath.Walk(path, func(path string, _ fs.FileInfo, _ error) error {
			if filepath.Ext(path) != ".svg" {
				return nil
			}

			return processSVG(path, f.Output, v)
		})
		if err != nil {
			log.Fatalf("error processing SVGs: %v", err)
		}
	}
}

func processSVG(inputPath, outputDir string, variant variant) error {
	data, err := os.ReadFile(filepath.Clean(inputPath))
	if err != nil {
		return err
	}

	var svg SVG
	err = xml.Unmarshal(data, &svg)
	if err != nil {
		return err
	}

	baseName := strings.TrimSuffix(filepath.Base(inputPath), ".svg")

	funcName := fmt.Sprintf("%s%s%s", ToCamelCase(baseName), cases.Title(language.English).String(variant.Size), cases.Title(language.English).String(variant.Type))
	outputFile := filepath.Join(outputDir, baseName+"-"+variant.Size+"-"+variant.Type+".go")

	tmpl, err := template.New("component").Parse(templ)
	if err != nil {
		return err
	}

	//nolint:mnd
	err = filex.MkdirAll(outputDir, 0o755)
	if err != nil {
		return err
	}

	output, err := os.Create(filepath.Clean(outputFile))
	if err != nil {
		return err
	}
	defer output.Close()

	err = tmpl.Execute(output, struct {
		FuncName       string
		Width          string
		Height         string
		ViewBox        string
		Paths          []Path
		Stroke         string
		Fill           string
		StrokeWidth    string
		DefaultClasses map[string]bool
	}{
		FuncName:       funcName,
		Width:          svg.Width,
		Height:         svg.Height,
		ViewBox:        svg.ViewBox,
		Stroke:         svg.Stroke,
		Fill:           svg.Fill,
		StrokeWidth:    svg.StrokeWidth,
		Paths:          svg.Paths,
		DefaultClasses: variant.ClassNames,
	})
	if err != nil {
		return err
	}

	return nil
}
